-- 023_offline_sync_client_ids.sql
-- Offline field inspection: the mobile client creates records without a
-- connection and pushes them later. A client-generated UUID on each record
-- makes the push idempotent (a retried upload never creates a duplicate).

ALTER TABLE verifications
    ADD COLUMN client_id UUID,
    ADD COLUMN client_started_at TIMESTAMPTZ;

ALTER TABLE inspection_observations ADD COLUMN client_id UUID;
ALTER TABLE verification_readings   ADD COLUMN client_id UUID;

CREATE UNIQUE INDEX uq_verifications_client_id
    ON verifications (client_id) WHERE client_id IS NOT NULL;
CREATE UNIQUE INDEX uq_inspection_observations_client_id
    ON inspection_observations (client_id) WHERE client_id IS NOT NULL;
CREATE UNIQUE INDEX uq_verification_readings_client_id
    ON verification_readings (client_id) WHERE client_id IS NOT NULL;

COMMENT ON COLUMN verifications.client_id IS 'UUID generated by the mobile app; makes sync push idempotent.';
COMMENT ON COLUMN verifications.client_started_at IS 'Device clock time at which the officer started the inspection (offline); start_time stays the server time of upload.';

-- Delta pull needs "changed since" lookups on the officer's assignments.
CREATE INDEX idx_verification_assignments_assignee_updated
    ON verification_assignments (assigned_to_id, updated_at);
